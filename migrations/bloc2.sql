-- Extension BLOC 2B du schéma de recrutement.
-- Prérequis : migrations/bloc1.sql puis migrations/b2a_recrutement.sql.
-- Les tables candidat, offre et candidature appartiennent au BLOC 2A et ne
-- sont pas recréées ici. Ce script est rejouable.

ALTER TABLE candidat ADD COLUMN IF NOT EXISTS identifiant VARCHAR(100);
ALTER TABLE candidat ADD COLUMN IF NOT EXISTS mot_de_passe VARCHAR(255);
ALTER TABLE candidat ADD COLUMN IF NOT EXISTS actif BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE candidat ADD COLUMN IF NOT EXISTS acces_cree BOOLEAN NOT NULL DEFAULT FALSE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_candidat_identifiant
    ON candidat(identifiant) WHERE identifiant IS NOT NULL;

ALTER TABLE candidature ADD COLUMN IF NOT EXISTS dossier_valide BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE candidature ADD COLUMN IF NOT EXISTS acces_cree BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE candidature ADD COLUMN IF NOT EXISTS note_finale NUMERIC(5,2);

ALTER TABLE candidature DROP CONSTRAINT IF EXISTS candidature_statut_check;
ALTER TABLE candidature DROP CONSTRAINT IF EXISTS ck_candidature_statuts_2a_2b;
ALTER TABLE candidature ADD CONSTRAINT ck_candidature_statuts_2a_2b CHECK (statut IN (
    'RECUE', 'RECU', 'A_ETUDIER', 'DOSSIER_VALIDE', 'TEST_TECHNIQUE', 'TEST_EN_COURS', 'TEST_OK',
    'ENTRETIEN_RH', 'ENTRETIEN_TECHNICIEN', 'ENTRETIEN_DG', 'CONFIRMATION_FINALE', 'RECRUTE',
    'ADMIS', 'REFUSE', 'ABSENT', 'EN_ATTENTE', 'NON_RETENUE', 'LISTE_ATTENTE', 'RETIREE'
));

CREATE TABLE IF NOT EXISTS test_technique (
    id_test_technique BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature INTEGER NOT NULL UNIQUE,
    date_debut TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_fin TIMESTAMP,
    statut VARCHAR(30) NOT NULL DEFAULT 'PROGRAMME'
        CHECK (statut IN ('PROGRAMME', 'EN_COURS', 'RELANCE', 'CORRIGE', 'ADMIS', 'REFUSE', 'ABSENT')),
    seuil_note NUMERIC(5,2) NOT NULL DEFAULT 0,
    note_generale NUMERIC(5,2) NOT NULL DEFAULT 0,
    relance BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_test_candidature FOREIGN KEY (id_candidature)
        REFERENCES candidature(id_candidature) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reponse_test_technique (
    id_reponse BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_test_technique BIGINT NOT NULL,
    question_ref VARCHAR(100) NOT NULL,
    type_question VARCHAR(30) NOT NULL DEFAULT 'CHOIX'
        CHECK (type_question IN ('CHOIX', 'QCM', 'LIBRE')),
    reponse_textuelle TEXT,
    note NUMERIC(5,2) NOT NULL DEFAULT 0,
    corrigee BOOLEAN NOT NULL DEFAULT FALSE,
    correct BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_reponse_test FOREIGN KEY (id_test_technique)
        REFERENCES test_technique(id_test_technique) ON DELETE CASCADE,
    CONSTRAINT uk_reponse_test_question UNIQUE (id_test_technique, question_ref)
);

CREATE INDEX IF NOT EXISTS idx_test_candidature ON test_technique(id_candidature);
CREATE INDEX IF NOT EXISTS idx_reponse_test ON reponse_test_technique(id_test_technique);
